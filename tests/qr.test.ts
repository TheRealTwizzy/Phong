describe('QR encoder', () => {
  for (const fixture of FIXTURES) {
    it(`matches an independent encoder: ${fixture.note}`, () => {
      const matrix = encodeQr(fixture.text, fixture.level);
      expect(matrix.version).toBe(fixture.version);
      expect(matrix.size).toBe(fixture.rows.length);
      const rendered = matrix.modules.map((row) => row.map((m) => (m ? '1' : '0')).join(''));
      expect(rendered).toEqual(fixture.rows);
    });
  }

  it('sizes the version to the payload', () => {
    // 17 + 4v modules a side, and the smallest version that fits wins.
    expect(encodeQr('a', 'M').size).toBe(21);
    expect(encodeQr('a', 'M').version).toBe(1);
    const long = encodeQr('z'.repeat(200), 'M');
    expect(long.version).toBe(10);
    expect(long.size).toBe(57);
  });

  it('places the three finder patterns and the timing rows', () => {
    const { modules, size } = encodeQr('https://phong.example/', 'M');
    for (const [top, left] of [
      [0, 0],
      [0, size - 7],
      [size - 7, 0],
    ]) {
      expect(modules[top][left]).toBe(true);
      expect(modules[top + 1][left + 1]).toBe(false);
      expect(modules[top + 2][left + 2]).toBe(true);
      expect(modules[top + 3][left + 3]).toBe(true);
    }
    // Timing patterns alternate, and were briefly being overwritten by the
    // format-information reservation at (8,6) and (6,8).
    for (let i = 8; i < size - 8; i++) {
      expect(modules[6][i]).toBe(i % 2 === 0);
      expect(modules[i][6]).toBe(i % 2 === 0);
    }
  });

  it('always sets the dark module', () => {
    for (const level of ['L', 'M', 'Q', 'H'] as const) {
      const m = encodeQr('phong', level);
      expect(m.modules[m.size - 8][8]).toBe(true);
    }
  });

  it('refuses a payload past the largest supported version', () => {
    expect(() => encodeQr('x'.repeat(3000), 'M')).toThrow(/too long/i);
  });

  it('renders one SVG path with a module per dark cell', () => {
    const matrix = encodeQr('phong', 'M');
    const path = qrToSvgPath(matrix, 4);
    const dark = matrix.modules.flat().filter(Boolean).length;
    expect(path.match(/M/g)?.length).toBe(dark);
    // The quiet zone is baked into the coordinates, so nothing is drawn
    // inside it and the caller only has to size the viewBox.
    expect(path).not.toMatch(/M[0-3] /);
  });
});
